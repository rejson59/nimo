def parse(text):
    glyphs = {}
    blocks = []
    cur = []
    for line in text.splitlines():
        if line.strip() == "" and cur:
            blocks.append(cur)
            cur = []
        elif line.strip():
            cur.append(line.rstrip())
    if cur:
        blocks.append(cur)
    for block in blocks:
        cp = int(block[0])
        rows = block[1:]
        if len(rows) != 7 or any(len(r) != 5 for r in rows):
            raise SystemExit(f"bad glyph U+{cp:04X}: {rows}")
        cols = []
        for c in range(5):
            b = 0
            for r in range(7):
                if rows[r][c] == "#":
                    b |= 1 << r
            cols.append(b)
        glyphs[cp] = cols
    return glyphs


def js_escape_key(cp):
    ch = chr(cp)
    if ch == "\\":
        return "\\\\"
    if ch == '"':
        return '\\"'
    return ch


def emit_js(glyphs, path):
    lines = [
        "/**",
        " * nimo 5x7 font — original pixel art for this project.",
        " * Column-major, bit 0 = top row. Cell step is 6x8 (1px gap).",
        " * Same bytes as firmware/nimo/nimo_font.h",
        " */",
        "export const FONT_W = 5;",
        "export const FONT_H = 7;",
        "export const CELL_W = 6;",
        "export const CELL_H = 8;",
        "",
        "/** @type {Record<string, number[]>} */",
        "export const FONT = {",
    ]
    for cp in sorted(glyphs):
        cols = ", ".join(f"0x{b:02x}" for b in glyphs[cp])
        ch = js_escape_key(cp)
        lines.append(f'  "\\u{cp:04x}": [{cols}],')
    lines.append("};")
    lines.append("")
    lines.append("export function font_cols(ch) {")
    lines.append("  return FONT[ch] || null;")
    lines.append("}")
    lines.append("")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def emit_h(glyphs, path):
    ascii_rows = []
    extra = []
    for cp in range(32, 127):
        cols = glyphs.get(cp, [0, 0, 0, 0, 0])
        ascii_rows.append(cols)
    for cp in sorted(glyphs):
        if cp < 32 or cp > 126:
            extra.append((cp, glyphs[cp]))
    lines = [
        "#pragma once",
        "#include <stdint.h>",
        "",
        "// nimo 5x7 font. Column-major, LSB = top row.",
        "// Generated by tools/build_font.py — keep in sync with js/firmware/nimo_font.js",
        "",
        "static const uint8_t NIMO_FONT_ASCII[95][5] = {",
    ]
    for i, cols in enumerate(ascii_rows):
        cp = 32 + i
        ch = chr(cp) if cp != 92 and cp != 39 else "?"
        comment = ""
        if 32 < cp < 127 and cp != 92:
            comment = f"  // {chr(cp)}"
        body = ", ".join(f"0x{b:02x}" for b in cols)
        lines.append(f"  {{{body}}},{comment}")
    lines.append("};")
    lines.append("")
    lines.append("struct NimoExtraGlyph { uint16_t cp; uint8_t col[5]; };")
    lines.append(f"static const NimoExtraGlyph NIMO_FONT_EXTRA[{len(extra)}] = {{")
    for cp, cols in extra:
        body = ", ".join(f"0x{b:02x}" for b in cols)
        lines.append(f"  {{0x{cp:04X}, {{{body}}}}},")
    lines.append("};")
    lines.append(f"static const int NIMO_FONT_EXTRA_COUNT = {len(extra)};")
    lines.append("")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def sheet(glyphs, path):
    from PIL import Image, ImageDraw

    items = sorted(glyphs)
    cols_n = 16
    rows_n = (len(items) + cols_n - 1) // cols_n
    scale = 4
    cell = 18 * scale
    im = Image.new("RGB", (cols_n * cell, rows_n * cell + 8), (20, 22, 18))
    dr = ImageDraw.Draw(im)
    for i, cp in enumerate(items):
        cx = (i % cols_n) * cell
        cy = (i // cols_n) * cell
        cols = glyphs[cp]
        for c in range(5):
            bits = cols[c]
            for r in range(7):
                if bits & (1 << r):
                    x = cx + (2 + c) * scale
                    y = cy + (8 + r) * scale
                    dr.rectangle([x, y, x + scale - 1, y + scale - 1], fill=(244, 241, 234))
        dr.text((cx + 2, cy + 1), f"U+{cp:04X}", fill=(120, 110, 80))
    im.save(path)


def main():
    glyphs = parse(RAW)
    emit_js(glyphs, ROOT / "js/firmware/nimo_font.js")
    emit_h(glyphs, ROOT / "firmware/nimo/nimo_font.h")
    sheet(glyphs, Path("/tmp/nimo-frames/font-sheet.png"))
    print(f"{len(glyphs)} glyphs")


if __name__ == "__main__":
    main()
